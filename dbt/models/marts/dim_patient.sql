    n_ipp,
    nom,
    nom_famille_1,
    nom_famille_2,
    sexe,
    date_naissance,
    type_piece_identite,
    n_piece_identite,
    etat_civil,
    type_patient,
    date_photo,
    modifie_par,
    cree_par,
