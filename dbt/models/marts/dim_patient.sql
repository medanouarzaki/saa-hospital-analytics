    dim_patient : toutes les colonnes de int_patients (SCD 2, une ligne par version de fiche),
    plus trois colonnes de validité par fonction de fenêtre. Bornes semi-ouvertes : valide_de
    inclus, valide_jusqu_a exclu (NULL pour la version courante) -- exactement la sémantique
    de generator/patients.py::version_en_vigueur (dernière version dont la date d'extraction
