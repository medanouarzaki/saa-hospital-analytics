        quartier,
        nationalite,
        telephone_1,
        telephone_2,
        telephone_3,
        telephone_4,
        avertissements_sms,
        email,
        avertissements_email,
        environnement,
        nom_pere,
        nom_mere,
        etat_naissance,
        ville_naissance,
        pays_naissance,
        quartier_naissance,
        commentaire,
        province,
        exitus,
        date_modification,
        date_extraction,
        date_extraction as valide_de
    from {{ ref('int_patients') }}
